import type { GuideDefinition } from "../../data/guideMeta";

/** The few guide fields tool pages need to link to their guides. */
export interface GuideLink {
  path: string;
  title: string;
  relatedTools: string[];
  category: GuideDefinition["category"];
  summary: string;
  featured: boolean;
}

export function buildGuideIndex(guides: GuideDefinition[]): GuideLink[] {
  return guides.map((g) => ({ path: g.path, title: g.title, relatedTools: g.relatedTools ?? [], category: g.category, summary: g.summary, featured: Boolean(g.featured) }));
}

/** Source of src/data/guideIndex.generated.ts — written by scripts/generate-seo-files.ts. */
export function renderGuideIndexModule(guides: GuideDefinition[]): string {
  return `// Generated by scripts/generate-seo-files.ts from src/data/guides.ts — do not edit by hand.
// Tool pages import this small index instead of the full guide content, so the
// text of every guide isn't downloaded on every tool page.
import type { GuideLink } from "../lib/seo/guideIndex";

export const GUIDE_INDEX: GuideLink[] = ${JSON.stringify(buildGuideIndex(guides), null, 2)};
`;
}
