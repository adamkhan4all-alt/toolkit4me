import { byNewest, toSummary, type ArticleSummary } from "../../data/blog/meta";
import type { BlogArticle } from "../../data/blog/types";

/** Published articles only, newest first. Drafts never reach the index, the loaders, the sitemap or the prerender. */
export function publishedArticles(articles: BlogArticle[]): BlogArticle[] {
  return articles.filter((a) => a.status === "published").sort(byNewest);
}

export function buildBlogIndex(articles: BlogArticle[]): ArticleSummary[] {
  return publishedArticles(articles).map(toSummary);
}

/**
 * Source of src/data/blog/blogIndex.generated.ts — written by scripts/generate-seo-files.ts.
 * Listing pages import only this small index; each article's full text is its own chunk, loaded on its page.
 */
export function renderBlogIndexModule(articles: BlogArticle[]): string {
  const published = publishedArticles(articles);
  const loaders = published.map((a) => `  ${JSON.stringify(a.slug)}: () => import("./articles/${a.slug}").then((m) => m.article),`).join("\n");
  return `// Generated by scripts/generate-seo-files.ts from src/data/blog/articles — do not edit by hand.
// Listing pages import this small index (no article text); each article loads as its own chunk.
import type { ArticleSummary } from "./meta";
import type { BlogArticle } from "./types";

export const BLOG_INDEX: ArticleSummary[] = ${JSON.stringify(buildBlogIndex(articles), null, 2)};

export const ARTICLE_LOADERS: Record<string, () => Promise<BlogArticle>> = {
${loaders}
};
`;
}
